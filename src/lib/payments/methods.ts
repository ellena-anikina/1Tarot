// Способы оплаты, которые показывает страница оплаты. Общие для сервера и браузера.
//
// Правило для покупателя одно: не пришла трактовка — деньги не списаны или вернулись.
// Карта — двухстадийная оплата (холдирование): сумма блокируется и списывается, когда трактовка готова.
// СБП так не умеет — перевод проходит сразу, поэтому если трактовка не пришла, деньги возвращаются.

export const PAY_METHODS = {
  sbp: {
    label: "СБП",
    hint: "QR-код или ссылка — подтвердите в приложении банка. Если трактовка не придёт, деньги вернутся.",
    /** сумма только блокируется до трактовки */
    hold: false,
  },
  card: {
    label: "Банковская карта",
    hint: "Сумма заблокируется на карте и спишется, только когда трактовка будет готова.",
    hold: true,
  },
} as const;

export type PayMethod = keyof typeof PAY_METHODS;

export const isPayMethod = (v: unknown): v is PayMethod => typeof v === "string" && v in PAY_METHODS;
