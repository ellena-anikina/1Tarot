/** Значение из реквизитов, а если его ещё нет — заметная пометка, чтобы пропуск бросался в глаза. */
function Fill({ value, label }: { value: string; label: string }) {
  if (value) return <>{value}</>;
  return <mark className={styles.todo}>[{label}]</mark>;
}

/** Пункты раздела с номерами вида «3.2»: на них ссылается текст оферты. */
function Points({ s, start, children }: { s: number; start?: number; children: React.ReactNode }) {
  return (
    <ol className={styles.points} start={start} style={{ "--s": `"${s}"` } as React.CSSProperties}>
      {children}
    </ol>
  );
}

function Email() {
  if (!SELLER.email) return <Fill value="" label="почта для связи" />;
  return <a href={`mailto:${SELLER.email}`}>{SELLER.email}</a>;
}

function formatDate(iso: string): string {
  const date = new Date(`${iso}T00:00:00Z`);
  return `${new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" })
    .format(date)
    .replace(/\s*г\.?$/, "")} г.`;
}

